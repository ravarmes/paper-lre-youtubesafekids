def fig_matriz_confusao(tax: dict) -> None:
    cm = np.array(tax["matriz_confusao"])
    labels = [CLASSES[c] for c in tax["labels"]]

    fig, ax = plt.subplots(figsize=(4.4, 3.8))
    vmax = cm.max()
    # Sequencial de matiz unico: a magnitude e a luminosidade.
    im = ax.imshow(cm, cmap="Blues", vmin=0, vmax=vmax)
    for i in range(3):
        for j in range(3):
            val = int(cm[i, j])
            pct = val / cm[i].sum() * 100 if cm[i].sum() else 0
            ax.text(j, i, f"{val}\n{pct:.1f}%", ha="center", va="center",
                    fontsize=9.5, color="white" if val > vmax * 0.55 else INK)
    ax.set_xticks([0, 1, 2])
    ax.set_yticks([0, 1, 2])
    ax.set_xticklabels(labels)
    ax.set_yticklabels(labels)
    ax.set_xlabel("Predicted class", labelpad=8)
    ax.set_ylabel("True class", labelpad=8)
    # Sem moldura e sem barra de cor: a celula ja traz numero e percentual, e a
    # escala continua seria decoracao redundante.
    ax.spines[["top", "right", "left", "bottom"]].set_visible(False)
    ax.tick_params(length=0)
    plt.tight_layout()
    plt.savefig(FIGURAS_EN / "fig02-confusion-matrix.png", dpi=300, bbox_inches="tight")
    plt.close(fig)
    print("salvo: figuras/en/fig02-confusion-matrix.png")


def fig_reranking(rr: dict) -> None:
    res, ks = rr["resultados"], rr["protocolo"]["ks"]

    fig, eixos = plt.subplots(1, 2, figsize=(9.0, 3.2))
    for sis in RERANK_ORDEM:
        larg_linha, traco = ESTILO_SISTEMA[sis]
        eixos[0].plot(ks, [res[sis][f"ndcg@{k}"] for k in ks], marker="o",
                      markersize=4, label=RERANK_ROTULOS[sis],
                      color=COR_SISTEMA[sis], linewidth=larg_linha, linestyle=traco)
    eixos[0].set_xlabel("k")
    eixos[0].set_ylabel("nDCG@k")
    eixos[0].set_title("Ranking quality (nDCG@k)")
    eixos[0].set_xticks(ks)
    eixos[0].set_ylim(0, 1.05)
    _limpa(eixos[0], "y")
    eixos[0].legend(loc="lower right")

    grupos = [f"P@{k}" for k in ks] + ["MAP"]
    chaves = [f"p@{k}" for k in ks] + ["map"]
    x = np.arange(len(grupos))
    larg = 0.2
    for i, sis in enumerate(RERANK_ORDEM):
        # Piso e teto ficam esmaecidos tambem nas barras, para que a comparacao
        # que importa -- entre os dois metodos -- salte primeiro.
        limite = sis in ("aleatorio", "oraculo")
        eixos[1].bar(x + (i - 1.5) * larg, [res[sis][c] for c in chaves],
                     larg * 0.88, label=RERANK_ROTULOS[sis],
                     color=COR_SISTEMA[sis], alpha=0.55 if limite else 1.0)
    eixos[1].set_xticks(x)
    eixos[1].set_xticklabels(grupos)
    eixos[1].set_ylabel("value")
    eixos[1].set_title("Precision at the top and MAP")
    eixos[1].set_ylim(0, 1.05)
    _limpa(eixos[1], "y")

    fig.tight_layout()
    fig.savefig(FIGURAS_EN / "fig05-reranking-evaluation.png", dpi=300)
    plt.close(fig)
    print("salvo: figuras/en/fig05-reranking-evaluation.png")


def figs_estudo_caso(ec: dict) -> None:
    """Duas figuras separadas, pelo mesmo motivo de gerar_tabelas_estudo_caso.py.

    Os rotulos do eixo x sao os TERMOS DE CONSULTA, mantidos em portugues por serem
    entradas do sistema; a traducao vai na legenda da figura no manuscrito.
    """
    videos = ec["videos"]
    termos = list(dict.fromkeys(v["termo"] for v in videos))
    cores = COR_ESTRATO

    fig1, ax1 = plt.subplots(figsize=(7.2, 3.6))

    # As duas faixas da Eq. (2) sombreadas ao fundo: a distancia entre elas e tres
    # vezes a variacao interna, que e o argumento da formulacao em forma visual.
    ax1.axhspan(0.70, 0.85, color=cores["A"], alpha=0.09, zorder=0)
    ax1.axhspan(0.10, 0.2333, color=cores["B"], alpha=0.09, zorder=0)
    ax1.text(len(termos) - 0.42, 0.775, "no-risk band", fontsize=6.5,
             color=cores["A"], ha="right", va="center", zorder=1)
