def tab_significancia(sig: dict) -> str:
    n = sig["n_teste"]

    def pval(p):
        return "$< 10^{-4}$" if p < 1e-4 else f"${num(p, 4)}$"

    linhas = []
    for chave, _ in BASELINES:
        c = sig["comparacoes"][chave]
        bs = c["bootstrap_f1_macro"]
        linhas.append(
            f"{BASELINES_LONGO[chave]} & {num(c['f1_macro']*100,2)} & "
            f"{num(bs['diferenca']*100,2)} & "
            # virgula, e nao o ponto-e-virgula do gerador em portugues: o texto corrido
            # do manuscrito em ingles escreve os intervalos como [1.81, 9.02].
            f"[{num(bs['ic95'][0]*100,2)}, {num(bs['ic95'][1]*100,2)}] & "
            f"{pval(bs['p'])} & {pval(c['mcnemar']['p'])} \\\\"
        )
    return f"""{AVISO}\\begin{{table}}[!t]
\\caption{{Significance of the differences between the proposed \\emph{{ensemble}} and each baseline, on the same test partition ({n} sentences). $\\Delta$F1 is the macro-F1 difference in percentage points, in favor of the proposed model; the interval and the $p$-value come from a paired bootstrap with 10,000 resamples. The last column reports the $p$-value of McNemar's test on accuracy.}}\\label{{tab:significancia}}
\\begin{{tabular*}}{{\\tblwidth}}{{@{{}}LRRRRR@{{}}}}
\\toprule
Baseline & Macro F1 & $\\Delta$F1 & 95\\% CI & $p$ (bootstrap) & $p$ (McNemar) \\\\
\\midrule
{chr(10).join(linhas)}
\\bottomrule
\\end{{tabular*}}
\\end{{table}}
"""


