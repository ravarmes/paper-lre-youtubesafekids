def tab_ablacao(payload: dict) -> str:
    n_desempates = payload["n_desempates"]
    ab = payload["variantes"]
    linhas = []
    for chave, d in ab.items():
        m, s = d["metricas"], d["desvio_desempate"]
        nome = ABLACAO_ROTULOS[chave]
        if chave == "proposta":
            nome = f"\\textbf{{{nome}}}"
        cels = " & ".join(
            num(m[k]) if s[k] < 5e-4 else f"{num(m[k])}\\,$\\pm$\\,{num(s[k])}"
            for k in ABLACAO_METRICAS
        )
        linhas.append(f"{nome} & {cels} & {d['n_valores_distintos']}/{d['n_videos']} \\\\")
    n_videos = next(iter(ab.values()))["n_videos"]
